/* The password of uhid_app, the limited MySQL user the API connects as.
   grants.sql creates the user and needs this password, which must not be
   written in any committed file. It comes from APP_DB_PASSWORD in .env; if
   that is missing (a fresh .env), a random one is generated and APPENDED to
   .env, so the API finds it there next time. Nothing already in .env is
   changed. Used by db:reset, db:install and db:restore. */

const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
// Root's login may live in .env.admin, away from the running site (I10).
// Loaded first: dotenv never overwrites a value already set.
require('dotenv').config({ path: path.join(__dirname, '..', '.env.admin') });
require('dotenv').config({ path: path.join(__dirname, '..', '.env') });

const ENV_FILE = path.join(__dirname, '..', '.env');

function appPassword() {
  if (process.env.APP_DB_PASSWORD) return process.env.APP_DB_PASSWORD;
  const pw = crypto.randomBytes(18).toString('base64url');
  const lead = fs.existsSync(ENV_FILE) && !fs.readFileSync(ENV_FILE, 'utf8').endsWith('\n') ? '\n' : '';
  fs.appendFileSync(ENV_FILE,
    `${lead}# Password for uhid_app, the limited MySQL user the API connects as.\n` +
    `# Generated by the database scripts; any value works.\nAPP_DB_USER=uhid_app\nAPP_DB_PASSWORD=${pw}\n`);
  process.env.APP_DB_USER = 'uhid_app';
  process.env.APP_DB_PASSWORD = pw;
  console.log('  (no APP_DB_PASSWORD in .env — generated one and added it)');
  return pw;
}

module.exports = { appPassword };
